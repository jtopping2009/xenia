// Stand-in artwork: a generic silhouette / record / note / play glyph for
// music (so nothing reads as a misspelled band name), initials for games.
void DrawArtPlaceholder(ImDrawList* dl, ImFont* font, ImVec2 p0, ImVec2 p1,
                        ArtPlaceholder placeholder, const std::string& name) {
  float w = p1.x - p0.x;
  float h = p1.y - p0.y;
  ImVec2 c((p0.x + p1.x) * 0.5f, (p0.y + p1.y) * 0.5f);
  float r = std::min(w, h) * 0.5f;
  if (placeholder == ArtPlaceholder::kInitials) {
    dl->AddRectFilledMultiColor(p0, p1, TileColorForName(name, 0.85f),
                                TileColorForName(name, 0.85f),
                                TileColorForName(name, 0.45f),
                                TileColorForName(name, 0.45f));
    std::string initials = TileInitials(name);
    float size = std::min(r * 0.9f, r * 2.0f / float(initials.size()));
    ImVec2 extent = font->CalcTextSizeA(size, FLT_MAX, 0.0f, initials.c_str());
    AddShadowedText(dl, font, size,
                    ImVec2(c.x - extent.x * 0.5f, c.y - extent.y * 0.5f),
                    IM_COL32(255, 255, 255, 255), initials);
    return;
  }
  // Music: a dark, subtly tinted backdrop.
  dl->AddRectFilledMultiColor(p0, p1, IM_COL32(58, 64, 72, 255),
                              IM_COL32(58, 64, 72, 255),
                              IM_COL32(28, 32, 38, 255),
                              IM_COL32(28, 32, 38, 255));
  const ImU32 glyph = IM_COL32(190, 198, 206, 255);
  const ImU32 accent = TileColorForName(name, 0.8f);
  switch (placeholder) {
    case ArtPlaceholder::kArtist: {
      // Head and shoulders, the shoulders clipped by the tile's bottom edge.
      dl->AddCircleFilled(ImVec2(c.x, p0.y + h * 0.38f), r * 0.34f, glyph, 32);
      dl->PushClipRect(p0, p1, true);
      dl->AddCircleFilled(ImVec2(c.x, p1.y + r * 0.42f), r * 0.82f, glyph, 48);
      dl->PopClipRect();
    } break;
    case ArtPlaceholder::kAlbum: {
      // A vinyl record: grooves, a colored label, the spindle hole.
      dl->AddCircleFilled(c, r * 0.84f, IM_COL32(14, 14, 16, 255), 48);
      for (float groove : {0.74f, 0.62f, 0.5f}) {
        dl->AddCircle(c, r * groove, IM_COL32(60, 62, 68, 255), 48,
                      std::max(1.0f, r * 0.02f));
      }
      dl->AddCircleFilled(c, r * 0.3f, accent, 32);
      dl->AddCircleFilled(c, r * 0.05f, IM_COL32(28, 32, 38, 255), 12);
    } break;
    case ArtPlaceholder::kTrack: {
      // An eighth note.
      ImVec2 head(c.x - r * 0.18f, c.y + r * 0.34f);
      float head_radius = r * 0.24f;
      dl->AddCircleFilled(head, head_radius, glyph, 24);
      float stem_x = head.x + head_radius * 0.82f;
      float stem_top = c.y - r * 0.56f;
      dl->AddRectFilled(ImVec2(stem_x - r * 0.08f, stem_top),
                        ImVec2(stem_x, head.y), glyph);
      dl->AddTriangleFilled(ImVec2(stem_x, stem_top),
                            ImVec2(stem_x + r * 0.4f, stem_top + r * 0.3f),
                            ImVec2(stem_x, stem_top + r * 0.34f), glyph);
    } break;
    case ArtPlaceholder::kPlay: {
      dl->AddCircleFilled(c, r * 0.7f, IM_COL32(72, 160, 32, 255), 40);
      dl->AddTriangleFilled(ImVec2(c.x - r * 0.22f, c.y - r * 0.34f),
                            ImVec2(c.x + r * 0.36f, c.y),
                            ImVec2(c.x - r * 0.22f, c.y + r * 0.34f),
                            IM_COL32(255, 255, 255, 255));
    } break;
    default:
      break;
  }
}
