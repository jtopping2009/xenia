// Draws `texture` filling p0-p1 like CSS object-fit: cover - cropped to the
// box's aspect ratio rather than stretched (artist photos are rarely square).
void AddImageCover(ImDrawList* dl, void* texture, ImVec2 p0, ImVec2 p1,
                   uint32_t width, uint32_t height) {
  float box_aspect = (p1.x - p0.x) / std::max(1.0f, p1.y - p0.y);
  float image_aspect = float(width) / float(std::max(1u, height));
  ImVec2 uv0(0.0f, 0.0f), uv1(1.0f, 1.0f);
  if (image_aspect > box_aspect) {
    float visible = box_aspect / image_aspect;
    uv0.x = (1.0f - visible) * 0.5f;
    uv1.x = uv0.x + visible;
  } else if (image_aspect < box_aspect) {
    float visible = image_aspect / box_aspect;
    // Bias toward the top - that's where faces are in artist photos.
    uv0.y = (1.0f - visible) * 0.25f;
    uv1.y = uv0.y + visible;
  }
  dl->AddImage(texture, p0, p1, uv0, uv1);
}

enum class TransportGlyph { kPrevious, kPlay, kPause, kNext };

// Media transport symbols, centered on `c` within about `r`.
void DrawTransportGlyph(ImDrawList* dl, ImVec2 c, float r,
                        TransportGlyph glyph, ImU32 color) {
  float h = r * 0.55f;
  switch (glyph) {
    case TransportGlyph::kPlay:
      dl->AddTriangleFilled(ImVec2(c.x - h * 0.7f, c.y - h),
                            ImVec2(c.x + h, c.y),
                            ImVec2(c.x - h * 0.7f, c.y + h), color);
      break;
    case TransportGlyph::kPause:
      dl->AddRectFilled(ImVec2(c.x - h * 0.8f, c.y - h),
                        ImVec2(c.x - h * 0.25f, c.y + h), color);
      dl->AddRectFilled(ImVec2(c.x + h * 0.25f, c.y - h),
                        ImVec2(c.x + h * 0.8f, c.y + h), color);
      break;
    case TransportGlyph::kPrevious:
    case TransportGlyph::kNext: {
      // A bar and a triangle pointing at it: |< or >|.
      float dir = glyph == TransportGlyph::kNext ? 1.0f : -1.0f;
      dl->AddTriangleFilled(ImVec2(c.x - dir * h * 0.8f, c.y - h),
                            ImVec2(c.x + dir * h * 0.5f, c.y),
                            ImVec2(c.x - dir * h * 0.8f, c.y + h), color);
      float bar_x = c.x + dir * h * 0.5f;
      dl->AddRectFilled(ImVec2(std::min(bar_x, bar_x + dir * h * 0.35f),
                               c.y - h),
                        ImVec2(std::max(bar_x, bar_x + dir * h * 0.35f),
                               c.y + h),
                        color);
    } break;
  }
}

