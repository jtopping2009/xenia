      float wrap = box_w - 56.0f * s;
      dl->PushClipRect(b0, b1, true);
      dl->AddText(font, 34.0f * s, ImVec2(b0.x + 28.0f * s, b0.y + 34.0f * s),
                  IM_COL32(40, 40, 40, 255), title.c_str(), nullptr, wrap);
      dl->AddText(font, 24.0f * s, ImVec2(b0.x + 28.0f * s, b0.y + 92.0f * s),
                  IM_COL32(100, 100, 100, 255), body.c_str(), nullptr, wrap);
