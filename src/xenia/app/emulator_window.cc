// Draws a genuinely rotated vertical tab label (the real Xbox Guide's side
// tabs read top-to-bottom, rotated 90 degrees rather than stacked
// letter-by-letter). ImGui's AddText has no native rotation support, so
// this uses the standard workaround: draw the text normally, then spin the
// vertices it just emitted 90 degrees clockwise (screen space, y-down:
// (x,y) -> (-y,x) relative to the pivot) around the point it was drawn
// from. `tab_center_x` is where the label should be horizontally centered
// once rotated; `top_y` is where it should start, near the top of the tab.
void DrawVerticalTabLabel(ImDrawList* draw_list, ImFont* font, float font_size,
                          float tab_center_x, float top_y, ImU32 color,
                          const std::string& label) {
  ImVec2 text_size = font->CalcTextSizeA(font_size, FLT_MAX, 0.0f, label.c_str());
  // Post-rotation, the text's bounding box spans [pivot.x - text_size.y,
  // pivot.x] horizontally - offset the pivot so that range ends up centered
  // on tab_center_x.
  ImVec2 pivot(tab_center_x + text_size.y * 0.5f, top_y);

  // AddText culls glyphs against the clip rect at their *unrotated*
  // positions, so a label near the right edge would lose its tail - clip to
  // a rect covering both the unrotated and rotated extents instead.
  draw_list->PushClipRect(
      ImVec2(pivot.x - text_size.y - 2.0f, pivot.y - text_size.y - 2.0f),
      ImVec2(pivot.x + text_size.x + 2.0f, pivot.y + text_size.x + 2.0f));
  int vtx_start = draw_list->VtxBuffer.Size;
  draw_list->AddText(font, font_size, pivot, color, label.c_str());
  int vtx_end = draw_list->VtxBuffer.Size;
  for (int i = vtx_start; i < vtx_end; ++i) {
    ImVec2& v = draw_list->VtxBuffer[i].pos;
    float rel_x = v.x - pivot.x;
    float rel_y = v.y - pivot.y;
    v.x = pivot.x - rel_y;
    v.y = pivot.y + rel_x;
  }
  draw_list->PopClipRect();
}

// Whether a No-Intro tag group is just a language list ("En,Ja,Fr") - too
// long to be useful on the dashboard, unlike region/disc/revision tags.
bool IsLanguageListTag(const std::string& group) {
  size_t start = 0;
  while (start <= group.size()) {
    size_t end = group.find(',', start);
    if (end == std::string::npos) {
      end = group.size();
    }
    std::string code = group.substr(start, end - start);
    if (code.size() != 2 ||
        !std::isupper(static_cast<unsigned char>(code[0])) ||
        !std::islower(static_cast<unsigned char>(code[1]))) {
      return false;
    }
    start = end + 1;
  }
  return true;
}

// Splits a game file/folder name into a clean title and its No-Intro-style
// tags, minus language lists: "Halo 3 (USA, Europe) (En,Fr) (Disc 1)" ->
// "Halo 3", "USA, Europe · Disc 1".
void SplitGameFileName(const std::string& name, std::string* title,
                       std::string* tags) {
  size_t first_group = name.find_first_of("([");
  std::string head = name.substr(0, first_group);
  size_t head_end = head.find_last_not_of(" _.-");
  *title = head_end == std::string::npos ? name : head.substr(0, head_end + 1);
  tags->clear();
  for (size_t pos = first_group; pos != std::string::npos;) {
    char close = name[pos] == '(' ? ')' : ']';
    size_t end = name.find(close, pos + 1);
    if (end == std::string::npos) {
      break;
    }
    std::string group = name.substr(pos + 1, end - pos - 1);
    if (!IsLanguageListTag(group)) {
      if (!tags->empty()) {
        *tags += " \xC2\xB7 ";
      }
      *tags += group;
    }
    pos = name.find_first_of("([", end + 1);
  }
}

std::string FormatByteSize(uint64_t bytes) {
  constexpr double kGiB = 1024.0 * 1024.0 * 1024.0;
  if (bytes >= uint64_t(kGiB)) {
    return fmt::format("{:.1f} GB", double(bytes) / kGiB);
  }
  return fmt::format("{} MB", bytes / (1024 * 1024));
}

// A stable per-name tile color, standing in for box art we don't have.
ImU32 TileColorForName(const std::string& name, float value) {
  uint32_t hash = 2166136261u;
  for (unsigned char c : name) {
    hash = (hash ^ c) * 16777619u;
  }
  float r, g, b;
  ImGui::ColorConvertHSVtoRGB(float(hash % 360) / 360.0f, 0.6f, value, r, g,
                              b);
  return ImGui::ColorConvertFloat4ToU32(ImVec4(r, g, b, 1.0f));
}

// Up to two initials ("Burnout Revenge" -> "BR"), for the stand-in tiles.
std::string TileInitials(const std::string& name) {
  std::string initials;
  bool at_word_start = true;
  for (char c : name) {
    bool is_alnum = std::isalnum(static_cast<unsigned char>(c)) != 0;
    if (is_alnum && at_word_start) {
      initials += char(std::toupper(static_cast<unsigned char>(c)));
      if (initials.size() == 2) {
        break;
      }
    }
    at_word_start = !is_alnum && c != '\'';
  }
  return initials.empty() ? "?" : initials;
}

void AddShadowedText(ImDrawList* draw_list, ImFont* font, float font_size,
                     ImVec2 pos, ImU32 color, const std::string& text,
                     float wrap_width = 0.0f) {
  float offset = std::max(1.0f, font_size * 0.06f);
  draw_list->AddText(font, font_size, ImVec2(pos.x + offset, pos.y + offset),
                     IM_COL32(0, 40, 0, 110), text.c_str(), nullptr,
                     wrap_width);
  draw_list->AddText(font, font_size, pos, color, text.c_str(), nullptr,
                     wrap_width);
}

