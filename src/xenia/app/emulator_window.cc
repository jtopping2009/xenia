void EmulatorWindow::GuideMenuOverlay::StartLeaveInPlace() {
  leave_in_progress_ = true;
  leave_fallback_started_ = false;
  leave_result_ = 0;
  leave_started_at_ = std::chrono::steady_clock::now();
  last_action_message_ = "Leaving game...";
  Emulator* emulator = emulator_window_.emulator();
  // Detached: if it never returns, the watchdog in PollLeaveInPlace restarts
  // Xenia, which ends it.
  std::thread([this, emulator] {
    xe::threading::set_name("Leave Game");
    leave_result_ = emulator->UnloadTitleInPlace() ? 1 : 2;
  }).detach();
}

void EmulatorWindow::GuideMenuOverlay::PollLeaveInPlace() {
  int result = leave_result_;
  if (result == 1) {
    leave_in_progress_ = false;
    last_action_message_.clear();
    // The title is gone - the dashboard takes over from here (IsDashboardMode).
    emulator_window_.app_context().CallInUIThread([this] {
      emulator_window_.window()->SetIcon(nullptr, 0);
      emulator_window_.UpdateTitle();
    });
    return;
  }
  bool timed_out = std::chrono::steady_clock::now() - leave_started_at_ >
                   std::chrono::seconds(8);
  if ((result == 2 || timed_out) && !leave_fallback_started_) {
    leave_fallback_started_ = true;
    XELOGW("Leave in place {} - restarting to the dashboard instead",
           result == 2 ? "failed" : "timed out");
    last_action_message_ = "Returning to the Xbox Dashboard...";
    emulator_window_.app_context().CallInUIThread(
        [this] { emulator_window_.RelaunchXenia({}); });
  }
}

void EmulatorWindow::GuideMenuOverlay::RunPendingAction() {
  std::filesystem::path target;
  if (pending_action_ == PendingAction::kTurnOff) {
    pending_action_ = PendingAction::kNone;
    last_action_message_ = "Turning off...";
    emulator_window_.app_context().CallInUIThread(
        [this] { emulator_window_.QuitXenia(); });
    return;
  }
  if (pending_action_ == PendingAction::kSwitchGame) {
    target = pending_game_path_;
    last_action_message_ = "Loading: " + pending_game_name_;
  } else if (cvars::launcher_mode) {
    // Back to the frontend - it resumes once this process exits.
    pending_action_ = PendingAction::kNone;
    last_action_message_ = "Quitting...";
    emulator_window_.app_context().CallInUIThread(
        [this] { emulator_window_.QuitXenia(); });
    return;
  } else if (cvars::leave_game_in_place) {
    pending_action_ = PendingAction::kNone;
    StartLeaveInPlace();
    return;
  } else {
    last_action_message_ = "Returning to the Xbox Dashboard...";
  }
  pending_action_ = PendingAction::kNone;
  // RelaunchXenia only returns if it couldn't start the new process.
  emulator_window_.app_context().CallInUIThread([this, target] {
    emulator_window_.RelaunchXenia(target);
    last_action_message_ = "Couldn't restart Xenia - see the log.";
  });
}

