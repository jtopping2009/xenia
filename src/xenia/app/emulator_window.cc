void EmulatorWindow::FileOpen() {
  std::filesystem::path path;

  auto file_picker = xe::ui::FilePicker::Create();
  file_picker->set_mode(ui::FilePicker::Mode::kOpen);
  file_picker->set_type(ui::FilePicker::Type::kFile);
  file_picker->set_multi_selection(false);
  file_picker->set_title("Select Content Package");
  file_picker->set_extensions({
      {"Supported Files", "*.iso;*.xex;*.*"},
      {"Disc Image (*.iso)", "*.iso"},
      {"Xbox Executable (*.xex)", "*.xex"},
      //{"Content Package (*.xcp)", "*.xcp" },
      {"All Files (*.*)", "*.*"},
  });
  if (file_picker->Show(window_.get())) {
    auto selected_files = file_picker->selected_files();
    if (!selected_files.empty()) {
      path = selected_files[0];
    }
  }

  if (!path.empty()) {
    // Normalize the path and make absolute.
    auto abs_path = std::filesystem::absolute(path);
    auto result = emulator_->LaunchPath(abs_path);
    if (XFAILED(result)) {
      // TODO: Display a message box.
      XELOGE("Failed to launch target: {:08X}", result);
    }
  }
}

void EmulatorWindow::FileClose() {
  if (emulator_->is_title_open()) {
    // Not TerminateTitle() - see RelaunchXenia.
    if (cvars::launcher_mode) {
      QuitXenia();
    } else {
      RelaunchXenia({});
    }
  }
}

void EmulatorWindow::StopMusicForExit() {
  if (!cvars::music_assistant_stop_on_exit ||
      cvars::music_assistant_host.empty()) {
    return;
  }
  // On its own thread, detached, so the wait below can give up on it - the
  // process's hard exit ends it either way.
  auto done = std::make_shared<std::promise<void>>();
  std::future<void> finished = done->get_future();
  std::thread([done] {
    apu::music_assistant::MusicAssistantClient client(
        cvars::music_assistant_host, uint16_t(cvars::music_assistant_port),
        cvars::music_assistant_token);
    std::string player_id;
    if (client.FindPlayerIdByName("Xenia", &player_id)) {
      client.QueueCommand(player_id, "stop");
      client.QueueCommand(player_id, "clear");
      XELOGI("StopMusicForExit: stopped and cleared Music Assistant queue {}",
             player_id);
    }
    done->set_value();
  }).detach();
  if (finished.wait_for(std::chrono::seconds(2)) !=
      std::future_status::ready) {
    XELOGW("StopMusicForExit: Music Assistant didn't answer in time");
  }
}

void EmulatorWindow::QuitXenia() {
  StopMusicForExit();
  // The config isn't saved here: settings changed in the guide are saved as
  // they change, and saving everything again on the way out would undo any
  // edits made to the config file while Xenia was running.
  XELOGI("QuitXenia: exiting");
  std::quick_exit(EXIT_SUCCESS);
}

void EmulatorWindow::RelaunchXenia(const std::filesystem::path& target) {
#if XE_PLATFORM_WIN32
  // The config isn't saved first (see QuitXenia) - the guide's settings are
  // already saved, and the new process reads the file as it is.

  std::wstring command_line =
      L"\"" + xe::filesystem::GetExecutablePath().wstring() + L"\"";
  command_line += window_->IsFullscreen() ? L" --fullscreen=true"
                                          : L" --fullscreen=false";
  if (!target.empty()) {
    command_line += L" \"--target=" + target.wstring() + L"\"";
  }
  if (IsInShell()) {
    command_line += L" --embed_parent_window=" +
                    std::to_wstring(cvars::embed_parent_window);
  }

  // Makes the new process wait for this one to fully exit before it starts
  // up (see wWinMain), so the two never contend for the log, config, shader
  // storage, devices, or the "Xenia" Music Assistant player name.
  SetEnvironmentVariableW(L"XENIA_RELAUNCH_WAIT_PID",
                          std::to_wstring(GetCurrentProcessId()).c_str());
  STARTUPINFOW startup_info = {};
  startup_info.cb = sizeof(startup_info);
  PROCESS_INFORMATION process_info = {};
  BOOL created = CreateProcessW(nullptr, command_line.data(), nullptr, nullptr,
                                FALSE, 0, nullptr, nullptr, &startup_info,
                                &process_info);
  SetEnvironmentVariableW(L"XENIA_RELAUNCH_WAIT_PID", nullptr);
  if (!created) {
    XELOGE("RelaunchXenia: CreateProcess failed ({})", GetLastError());
    return;
  }
  CloseHandle(process_info.hThread);
  CloseHandle(process_info.hProcess);

  XELOGI("RelaunchXenia: started new instance{}, exiting",
         target.empty() ? std::string(" on the dashboard")
                        : " on " + xe::path_to_utf8(target));
  // Same hard exit a normal window close ends in (EmulatorApp::OnDestroy) -
  // deliberately never stops the running title in-process. The exit code
  // tells a shell to wait for the new instance rather than go home.
  std::quick_exit(kRelaunchExitCode);
#else
  XELOGE("RelaunchXenia: not implemented on this platform");
#endif
}

void EmulatorWindow::ShowContentDirectory() {
  std::filesystem::path target_path;

  auto content_root = emulator_->content_root();
  if (!emulator_->is_title_open() || !emulator_->kernel_state()) {
    target_path = content_root;
  } else {
    // TODO(gibbed): expose this via ContentManager?
    auto title_id =
        fmt::format("{:08X}", emulator_->kernel_state()->title_id());
    auto package_root = content_root / title_id;
    target_path = package_root;
  }

  if (!std::filesystem::exists(target_path)) {
    std::filesystem::create_directories(target_path);
  }

  LaunchFileExplorer(target_path);
}

